def build():
    courses = []
    seen = set()
    for domain, _, _, _ in DOMAINS:
        for cid, title, level, prereqs, summary, objectives, keywords in C.get(domain, []):
            if cid in seen:
                raise ValueError("id duplique: " + cid)
            seen.add(cid)
            courses.append({
                "id": cid,
                "title": title,
                "domain": domain,
                "level": level,
                "prereqs": prereqs,
                "summary": summary,
                "objectives": objectives,
                "keywords": keywords,
            })

    ids = {c["id"] for c in courses}
    for c in courses:
        for p in c["prereqs"]:
            if p not in ids:
                raise ValueError("prerequis inconnu %s pour %s" % (p, c["id"]))

    # detection de cycle
    color = {}

    def visit(node, stack):
        state = color.get(node, 0)
        if state == 1:
            raise ValueError("cycle de prerequis: " + " -> ".join(stack + [node]))
        if state == 2:
            return
        color[node] = 1
        by_id = {c["id"]: c for c in courses}
        for p in by_id[node]["prereqs"]:
            visit(p, stack + [node])
        color[node] = 2

    for c in courses:
        visit(c["id"], [])

    for tid, t in TRACKS.items():
        if t["goal"] not in ids:
            raise ValueError("objectif de parcours inconnu: " + t["goal"])
        for e in t["extra"]:
            if e not in ids:
                raise ValueError("cours de parcours inconnu: " + e)

    data = {
        "version": 1,
        "domains": [
            {"id": d, "name": n, "description": desc, "color": col}
            for d, n, desc, col in DOMAINS
        ],
        "levels": [{"value": k, "name": v} for k, v in sorted(LEVEL_NAMES.items())],
        "tracks": [
            {"id": k, "title": v["title"], "goal": v["goal"], "extra": v["extra"]}
            for k, v in TRACKS.items()
        ],
        "courses": courses,
    }
    return data


